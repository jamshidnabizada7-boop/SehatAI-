export function glossaryForPrompt(query?: string): string {
  if (!query) {
    return GLOSSARY.slice(0, 20).map((g) => `${g.en} = ${g.ur} = ${g.roman}`).join('\n');
  }
  const q = query.toLowerCase();
  const matched = GLOSSARY.filter(
    (g) => q.includes(g.en.toLowerCase()) || q.includes(g.roman.toLowerCase()) || query.includes(g.ur)
  );
  const selected = matched.length > 0 ? matched : GLOSSARY.slice(0, 20);
  return selected.slice(0, 25).map((g) => `${g.en} = ${g.ur} = ${g.roman}`).join('\n');
}
